"""Render converted manifests as files: plain Kubernetes YAML, or a Helm chart.

The output is proportional to the input: one file per resource that the compose file
needs, and nothing else. A Helm chart adds only Chart.yaml and a values.yaml holding the
things people change between environments (image, replicas, resources, storage size).
"""

from __future__ import annotations

import re
from typing import Any

import yaml

from converters.compose_to_k8s import ComposeError, to_k8s_name

OUTPUTS = ("manifests", "helm")
# Resource kinds in the order the files are listed and applied: a namespace before what
# goes in it, storage before the workloads that mount it, workloads before their Services.
_ORDER = ("namespaces", "persistent_volume_claims", "deployments", "services")
_FILE_SUFFIX = {
    "namespaces": "namespace",
    "persistent_volume_claims": "pvc",
    "deployments": "deployment",
    "services": "service",
}
_CHART_NAME_INVALID = re.compile(r"[^a-z0-9-]+")

# Sentinels: dumped by PyYAML as plain text, then swapped for Helm template expressions.
_SENTINEL = "__HELM_{kind}_{name}__"


def render_files(
    result: dict[str, Any], output: str = "manifests", chart_name: str | None = None
) -> list[dict[str, str]]:
    """Turn a convert_compose_to_k8s() result into a list of {"path", "content"} files.

    output="manifests": one YAML file per resource, in apply order.
    output="helm": a chart with Chart.yaml, values.yaml and one template per resource.
    """
    if output not in OUTPUTS:
        raise ComposeError(f"Unknown output '{output}'. Use one of: {', '.join(OUTPUTS)}")
    manifests = result["manifests"]
    if output == "manifests":
        return [
            {"path": _file_name(kind, resource), "content": _dump(resource)}
            for kind in _ORDER
            for resource in manifests.get(kind, [])
        ]
    return _render_chart(manifests, chart_name or "app")


def _file_name(kind: str, resource: dict[str, Any]) -> str:
    return f"{resource['metadata']['name']}-{_FILE_SUFFIX[kind]}.yaml"


def _dump(document: Any) -> str:
    return yaml.safe_dump(document, sort_keys=False, default_flow_style=False)


def chart_name_from(compose: dict[str, Any]) -> str:
    """A chart name from the compose file's top-level `name`, or 'app'."""
    raw = compose.get("name") if isinstance(compose, dict) else None
    if not raw:
        return "app"
    cleaned = _CHART_NAME_INVALID.sub("-", str(raw).lower()).strip("-")
    return cleaned[:63].rstrip("-") or "app"


def _render_chart(
    manifests: dict[str, list[dict[str, Any]]], chart_name: str
) -> list[dict[str, str]]:
    values: dict[str, Any] = {}
    files: list[dict[str, str]] = []

    workloads: dict[str, Any] = {}
    for deployment in manifests.get("deployments", []):
        name = deployment["metadata"]["name"]
        container = deployment["spec"]["template"]["spec"]["containers"][0]
        entry: dict[str, Any] = {
            "image": container["image"],
            "replicas": deployment["spec"]["replicas"],
        }
        if "resources" in container:
            entry["resources"] = container["resources"]
        workloads[name] = entry
        files.append(
            {
                "path": f"templates/{name}-deployment.yaml",
                "content": _templated_deployment(deployment, name),
            }
        )
    if workloads:
        values["services"] = workloads

    storage: dict[str, Any] = {}
    for pvc in manifests.get("persistent_volume_claims", []):
        name = pvc["metadata"]["name"]
        storage[name] = {"size": pvc["spec"]["resources"]["requests"]["storage"]}
        files.append({"path": f"templates/{name}-pvc.yaml", "content": _templated_pvc(pvc, name)})
    if storage:
        values["volumes"] = storage

    for service in manifests.get("services", []):
        name = service["metadata"]["name"]
        files.append(
            {
                "path": f"templates/{name}-service.yaml",
                "content": _dump(_without_namespace(service)),
            }
        )

    chart = {
        "apiVersion": "v2",
        "name": chart_name,
        "description": "Generated by DevToolkit from a docker-compose file",
        "type": "application",
        "version": "0.1.0",
        "appVersion": "0.1.0",
    }
    return [
        {"path": "Chart.yaml", "content": _dump(chart)},
        {"path": "values.yaml", "content": _dump(values)},
        *files,
    ]


def _without_namespace(resource: dict[str, Any]) -> dict[str, Any]:
    """Helm puts resources in the release namespace, so templates carry none."""
    copy = dict(resource)
    copy["metadata"] = {k: v for k, v in resource["metadata"].items() if k != "namespace"}
    return copy


def _values_ref(section: str, name: str) -> str:
    # Names can contain '-', which Go templates can't take after a dot, so use index.
    return f'(index .Values.{section} "{name}")'


def _templated_deployment(deployment: dict[str, Any], name: str) -> str:
    doc = _without_namespace(deployment)
    spec = dict(doc["spec"])
    template = dict(spec["template"])
    pod = dict(template["spec"])
    container = dict(pod["containers"][0])

    container["image"] = _SENTINEL.format(kind="image", name=name)
    spec["replicas"] = _SENTINEL.format(kind="replicas", name=name)
    has_resources = "resources" in container
    if has_resources:
        container["resources"] = _SENTINEL.format(kind="resources", name=name)
    pod["containers"] = [container, *pod["containers"][1:]]
    template["spec"] = pod
    spec["template"] = template
    doc["spec"] = spec

    text = _dump(doc)
    ref = _values_ref("services", name)
    text = text.replace(_SENTINEL.format(kind="image", name=name), f"{{{{ {ref}.image | quote }}}}")
    text = text.replace(_SENTINEL.format(kind="replicas", name=name), f"{{{{ {ref}.replicas }}}}")
    if has_resources:
        # The sentinel sits on its own line as `resources: __...__`; replace the value with
        # a toYaml block indented under the key.
        text = re.sub(
            r"^(\s*)resources: " + re.escape(_SENTINEL.format(kind="resources", name=name)) + "$",
            lambda m: (
                f"{m.group(1)}resources:\n"
                f"{m.group(1)}  {{{{- toYaml {ref}.resources | nindent {len(m.group(1)) + 2} }}}}"
            ),
            text,
            flags=re.M,
        )
    return text


def _templated_pvc(pvc: dict[str, Any], name: str) -> str:
    doc = _without_namespace(pvc)
    spec = dict(doc["spec"])
    resources = dict(spec["resources"])
    resources["requests"] = {"storage": _SENTINEL.format(kind="storage", name=name)}
    spec["resources"] = resources
    doc["spec"] = spec
    text = _dump(doc)
    return text.replace(
        _SENTINEL.format(kind="storage", name=name),
        f"{{{{ {_values_ref('volumes', name)}.size | quote }}}}",
    )


__all__ = ["OUTPUTS", "chart_name_from", "render_files", "to_k8s_name"]
